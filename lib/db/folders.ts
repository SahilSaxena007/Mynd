import { FOLDER_PALETTE } from "../../components/folder-colors";
import { DEFAULT_GROUPING } from "./seed";
import { createFolder, getFolderBySlug, listFolders } from "./queries";
import { query, withTransaction } from "./transaction";

export class FolderError extends Error {
  constructor(message: string, public status = 400) { super(message); }
}
type Input = { name?: unknown; description?: unknown; color?: unknown; confirmOverLimit?: unknown };

function validate(input: Input, storedDescription?: string | null) {
  const name = typeof input.name === "string" ? input.name.trim() : "";
  const description = typeof input.description === "string" ? input.description.trim() : "";
  if (!name) throw new FolderError("Give the folder a name.");
  if (name.length > 40) throw new FolderError("Keep the folder name to 40 characters.");
  if (!description) throw new FolderError("Say what goes in this folder — the organiser files by this line.");
  // An unchanged stored rule (including seed rules) must remain editable. The
  // default suffix is generated by us, so it does not consume the user's limit.
  const userDescription = storedDescription !== undefined && description.endsWith(` ${DEFAULT_GROUPING}`)
    ? description.slice(0, -(DEFAULT_GROUPING.length + 1)) : description;
  if (description !== storedDescription && userDescription.length > 300) {
    throw new FolderError("Keep what goes in this folder to 300 characters.");
  }
  if (input.color !== undefined && (typeof input.color !== "string" || !FOLDER_PALETTE.includes(input.color))) {
    throw new FolderError("Choose a folder colour from the palette.");
  }
  return { name, description, color: input.color as string | undefined };
}

function withGrouping(description: string) {
  return /GROUPING:/i.test(description) ? description : `${description} ${DEFAULT_GROUPING}`;
}

async function rejectDuplicate(name: string, slug?: string) {
  const duplicate = await query("SELECT id FROM folders WHERE lower(name) = lower($1) AND ($2::text IS NULL OR slug <> $2)", [name, slug ?? null]);
  if (duplicate.rows.length) throw new FolderError(`You already have a folder called ${name}.`, 409);
}

export async function createUserFolder(input: Input) {
  return withTransaction(async () => {
    await query("SELECT pg_advisory_xact_lock(715004)");
    const { name, description, color } = validate(input);
    await rejectDuplicate(name);
    const count = Number((await query<{ count: string }>("SELECT count(*) FROM folders")).rows[0].count);
    if (count >= 10 && input.confirmOverLimit !== true) return { needsConfirm: true as const, count };
    const folders = await listFolders();
    const base = name.toLowerCase().replace(/[^a-z0-9]+/g, "-").slice(0, 40).replace(/^-+|-+$/g, "") || "folder";
    let slug = base;
    for (let suffix = 2; folders.some((folder) => folder.slug === slug); suffix++) {
      const ending = `-${suffix}`;
      slug = `${base.slice(0, 40 - ending.length).replace(/-+$/g, "")}${ending}`;
    }
    const folder = await createFolder({ name, slug, description: withGrouping(description),
      color: color ?? FOLDER_PALETTE.find((value) => !folders.some((folder) => folder.color === value)) ?? FOLDER_PALETTE[0] });
    return { folder };
  });
}

export async function updateUserFolder(slug: string, input: Input) {
  return withTransaction(async () => {
    await query("SELECT pg_advisory_xact_lock(715004)");
    await query("SELECT id FROM folders WHERE slug = $1 FOR UPDATE", [slug]);
    const previous = await getFolderBySlug(slug);
    if (!previous) throw new FolderError("Folder not found.", 404);
    const fixed = slug === "journal" || slug === "inbox";
    if (fixed && input.description !== previous.description) throw new FolderError("This folder's rule is fixed.");
    const { name, description, color } = validate(input, previous.description);
    await rejectDuplicate(name, slug);
    await query("UPDATE folders SET name = $2, description = $3, color = $4 WHERE slug = $1",
      [slug, name, fixed ? previous.description : withGrouping(description), color ?? previous.color]);
    return (await getFolderBySlug(slug))!;
  });
}
